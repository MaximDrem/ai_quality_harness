"""Схема structured output судьи-LLM: наблюдения и бинарный вердикт.

Модель возвращает JSON по этой схеме, поля читаются в `example/judge/`.
"""
from __future__ import annotations

from pydantic import BaseModel, Field


class JudgeResult(BaseModel):
    """Структурированный ответ судьи: наблюдения по метрике и бинарный вердикт."""

    observations: str = Field(
        description=(
            "Факты по проверяемой метрике: по одному короткому пункту на слайд "
            "('Слайд 1: ...', 'Слайд 2: ...'). Только наблюдения, относящиеся "
            "к CHECK_INSTRUCTION, без оценок и вердиктов. Если слайд не "
            "содержит релевантных элементов — так и пиши ('Слайд 5: нет "
            "таблиц/списков — нечего оценивать')."
        )
    )

    defect_slides: str = Field(
        description=(
            "Номера слайдов, где метрика нарушена, через запятую "
            "(например '1, 4'). Пустая строка, если нарушений нет."
        )
    )

    success: str = Field(
        description=(
            '"True" если проверяемый фактор соблюден (порог из '
            'CHECK_INSTRUCTION не превышен), "failed" если нарушен'
        )
    )

    reason: str = Field(
        description=(
            "Итоговое обоснование в 1-3 предложения: что нарушено и на каких "
            "слайдах (по defect_slides) ИЛИ подтверждение, что метрика "
            "соблюдена. Не упоминать дефекты других метрик вообще."
        )
    )